export interface GuideStep {
  /** 一句话操作 */
  text: string;
  /** 可选补充（显示为小字，说明"为什么"或"注意什么"） */
  tip?: string;
}

export interface GuideFeature {
  /** 锚点 id，页内目录跳转用 */
  id: string;
  /** 所属左侧菜单分组 */
  group: string;
  /** 菜单里的名字 */
  title: string;
  /** 页面真实地址（可复制到浏览器、也可点「打开这个页面」直达） */
  path: string;
  /** 谁能看到这个菜单 */
  roles: Role[];
  /** 一句话：它是干什么的 */
  purpose: string;
  /** 什么时候用它 */
  when: string;
  /** 分步操作 */
  steps: GuideStep[];
  /** 注意事项（红色高亮） */
  cautions?: string[];
}

export interface GuideCallout {
  kind: "tip" | "warn" | "danger";
  title: string;
  text: string;
}

export interface GuideFlow {
  id: string;
  title: string;
  /** 什么时候走这条流程（真实场景） */
  scenario: string;
  roles: Role[];
  steps: Array<{
    /** 这一步的名字 */
    title: string;
    /** 具体怎么做 */
    detail: string;
    /** 涉及的页面 */
    link?: { label: string; path: string };
  }>;
  cautions?: GuideCallout[];
}

export interface GuideFaq {
  id: string;
  /** 用户会怎么描述这个问题（用大白话，不用术语） */
  symptom: string;
  /** 为什么会这样 */
  cause: string;
  /** 怎么办（分步） */
  fix: string[];
}

export interface MenuGroup {
  /** 分组名（与左侧菜单一致） */
  name: string;
  /** 显示位置：数字越小越靠上 */
  rank: number;
  roles: Role[];
  /** 一句话说明这个分组装了什么 */
  summary: string;
}

